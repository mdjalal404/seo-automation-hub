// Writes .env.local for local development from `supabase status`.
// Generates a fresh credential encryption key and cron secret. Never run against production.
import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";

const hex = (n) => randomBytes(n).toString("hex");
// Development-only settings for the local Webflow / Shopify / custom CMS mocks (scripts/mock-cms.ts).
const multiCmsLines = () => [
  "# Local CMS mocks. The *_BASE_URL overrides are ignored when APP_ENV=production.",
  "MOCK_WEBFLOW_PORT=8788",
  `MOCK_WEBFLOW_TOKEN=${hex(32)}`,
  "WEBFLOW_API_BASE_URL=http://localhost:8788/v2",
  "MOCK_SHOPIFY_PORT=8789",
  `MOCK_SHOPIFY_TOKEN=shpat_${hex(16)}`,
  "SHOPIFY_ADMIN_BASE_URL=http://localhost:8789",
  "MOCK_CUSTOM_PORT=8790",
  `MOCK_CUSTOM_TOKEN=${randomBytes(24).toString("base64url")}`,
];

const force = process.argv.includes("--force");
if (existsSync(".env.local") && !force) {
  // Add settings introduced after the file was generated, keeping existing values.
  const existing = readFileSync(".env.local", "utf8");
  const missing = multiCmsLines().filter((l) => l.startsWith("#") ? false : !new RegExp(`^${l.split("=")[0]}=`, "m").test(existing));
  if (missing.length) {
    appendFileSync(".env.local", `\n# Added by setup-local-env.mjs\n${missing.join("\n")}\n`);
    console.log(`Added ${missing.length} new local development settings to .env.local (values generated, not printed).`);
  } else {
    console.log(".env.local already exists. Re-run with --force to overwrite.");
  }
  process.exit(0);
}
let status;
try {
  status = execSync("npx supabase status -o env", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
} catch {
  console.error("Could not read local Supabase status. Start it first: npx supabase start");
  process.exit(1);
}
const get = (k) => (status.match(new RegExp(`^${k}="?([^"\\n]+)"?`, "m")) ?? [])[1];
const apiUrl = get("API_URL");
const anon = get("ANON_KEY");
const service = get("SERVICE_ROLE_KEY");
if (!apiUrl || !anon || !service) {
  console.error("Supabase status did not include API_URL / ANON_KEY / SERVICE_ROLE_KEY.");
  process.exit(1);
}
const alnum = () => randomBytes(18).toString("base64").replace(/[^A-Za-z0-9]/g, "").padEnd(24, "x").slice(0, 24);
const lines = [
  "# Generated by scripts/setup-local-env.mjs for LOCAL DEVELOPMENT ONLY.",
  "APP_ENV=development",
  "NEXT_PUBLIC_APP_URL=http://localhost:3000",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}`,
  `SUPABASE_SERVICE_ROLE_KEY=${service}`,
  `CREDENTIAL_ENCRYPTION_KEY=${randomBytes(32).toString("base64")}`,
  "CREDENTIAL_ENCRYPTION_KEY_ID=k1",
  `CRON_SECRET=${randomBytes(24).toString("hex")}`,
  "# Allows connecting to the local mock WordPress (ignored when APP_ENV=production).",
  "ALLOW_PRIVATE_NETWORK_TARGETS=true",
  "WORKER_POLL_INTERVAL_MS=3000",
  "MOCK_WP_PORT=8787",
  "MOCK_WP_USER=demo-editor",
  `MOCK_WP_APP_PASSWORD=${alnum()}`,
  `DEMO_USER_PASSWORD=${randomBytes(12).toString("base64url")}`,
  ...multiCmsLines(),
  "",
];
writeFileSync(".env.local", lines.join("\n"), { mode: 0o600 });
console.log("Wrote .env.local (local development values; secrets were generated, not printed).");
